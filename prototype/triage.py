#!/usr/bin/env python3
"""Small, standard-library-only proposal triage demonstrator (Python 3.10+)."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
from datetime import datetime, timezone
from decimal import Decimal, ROUND_HALF_UP
from urllib import error, request

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "prototype" / "config.json"
FACTS = ROOT / "prototype" / "demo_facts.json"
PROMPTS = ROOT / "PROMPTS.md"
MAX_SOURCE_CHARS = 16000
ENDPOINT = "https://api.openai.com/v1/responses"


def strict_loads(text):
    def pairs(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError(f"Duplicate JSON property: {key}")
            result[key] = value
        return result

    def invalid_constant(_):
        raise ValueError("Non-finite JSON number")

    return json.loads(text, object_pairs_hook=pairs, parse_constant=invalid_constant)


def load(path):
    return strict_loads(Path(path).read_text(encoding="utf-8"))


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False).encode("utf-8")


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def save(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False,
                               allow_nan=False) + "\n", encoding="utf-8")


def number(value):
    if type(value) not in (int, float) or not Decimal(str(value)).is_finite():
        raise ValueError("Expected a finite number, not a boolean or string")
    return Decimal(str(value))


def validate_schema(value, schema, where="response"):
    """Validate exactly the JSON Schema subset generated by extraction_schema."""
    types = schema.get("type", [])
    if isinstance(types, str):
        types = [types]
    matches = {
        "null": value is None,
        "object": isinstance(value, dict),
        "array": isinstance(value, list),
        "string": isinstance(value, str),
        "boolean": type(value) is bool,
        "integer": type(value) is int,
        "number": type(value) in (int, float),
    }
    if types and not any(matches.get(t, False) for t in types):
        raise ValueError(f"{where}: invalid type")
    if type(value) in (int, float):
        numeric = number(value)
        if "minimum" in schema and numeric < number(schema["minimum"]):
            raise ValueError(f"{where}: value below minimum")
    if "enum" in schema and value not in schema["enum"]:
        raise ValueError(f"{where}: invalid enum")
    if value is None:
        return
    if isinstance(value, dict):
        props = schema.get("properties", {})
        if any(key not in value for key in schema.get("required", [])):
            raise ValueError(f"{where}: missing property")
        if schema.get("additionalProperties") is False and set(value) - set(props):
            raise ValueError(f"{where}: unexpected property")
        for key, item in value.items():
            if key in props:
                validate_schema(item, props[key], f"{where}.{key}")
    if isinstance(value, list):
        for index, item in enumerate(value):
            validate_schema(item, schema["items"], f"{where}[{index}]")


def criterion_fields(criterion):
    kind = criterion["kind"]
    if kind in ("target", "inverse_linear"):
        return [criterion["field"]]
    if kind == "composite":
        return [p["field"] for p in criterion["parts"]]
    if kind == "checklist":
        return criterion["fields"]
    raise ValueError("Unsupported scoring kind")


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError("Configuration must be a JSON object")
    if not isinstance(config.get("version"), str) or not config["version"].strip():
        raise ValueError("Configuration needs a version")
    fields = config.get("fields", [])
    if not isinstance(fields, list) or any(not isinstance(f, dict) or "id" not in f or "type" not in f for f in fields):
        raise ValueError("Configuration fields must be field-definition objects")
    types = {f["id"]: f["type"] for f in fields}
    if not fields or len(types) != len(fields):
        raise ValueError("Field IDs must be nonempty and unique")
    for name, kind in types.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
            raise ValueError("Invalid field identifier")
        if kind not in {"boolean", "number", "integer"}:
            raise ValueError("Unsupported field type")
    criteria = config.get("criteria", [])
    if not isinstance(criteria, list) or any(not isinstance(c, dict) for c in criteria):
        raise ValueError("Criteria must be a list of objects")
    ids = [c["id"] for c in criteria]
    if not ids or len(ids) != len(set(ids)):
        raise ValueError("Criterion IDs must be unique")
    weights = [number(c["weight"]) for c in criteria]
    if any(w < 0 for w in weights) or sum(weights) != 100:
        raise ValueError("Weights must be nonnegative and sum to 100")
    for c in criteria:
        used = criterion_fields(c)
        if not used or len(set(used)) != len(used) or any(f not in types for f in used):
            raise ValueError("Invalid criterion field references")
        if c["kind"] == "checklist":
            if any(types[f] != "boolean" for f in used):
                raise ValueError("Checklist fields must be booleans")
        elif any(types[f] == "boolean" for f in used):
            raise ValueError("Numeric rubric cannot use boolean fields")
        if c["kind"] == "target" and number(c["target"]) <= 0:
            raise ValueError("Target must be positive")
        if c["kind"] == "inverse_linear":
            if not 0 <= number(c["full_at"]) < number(c["zero_at"]):
                raise ValueError("Invalid full/zero anchors")
        if c["kind"] == "composite":
            if any(number(p["target"]) <= 0 or number(p["share"]) < 0 for p in c["parts"]):
                raise ValueError("Invalid composite target/share")
            if sum(number(p["share"]) for p in c["parts"]) != 1:
                raise ValueError("Composite shares must sum to 1")
    req_ids = []
    for rule in config.get("requirements", []):
        req_ids.append(rule["id"])
        field = rule["field"]
        if field not in types or rule["op"] not in {"is_true", "gte", "lte"}:
            raise ValueError("Invalid requirement")
        if rule["op"] == "is_true":
            if types[field] != "boolean":
                raise ValueError("Boolean requirement has non-boolean field")
        elif types[field] == "boolean" or number(rule["value"]) < 0:
            raise ValueError("Invalid numeric requirement")
    if not req_ids or len(set(req_ids)) != len(req_ids):
        raise ValueError("Requirement IDs must be nonempty and unique")
    codes = config.get("review_warning_codes", [])
    if not codes or len(set(codes)) != len(codes):
        raise ValueError("Review warning codes must be unique")
    if any(code not in config.get("warning_reasons", {}) for code in codes):
        raise ValueError("Every warning needs an explanation")
    for item in config.get("tie_break", []):
        if item["direction"] not in {"asc", "desc"}:
            raise ValueError("Invalid tie-break direction")
        source, field = item["source"], item["field"]
        if source == "criterion" and field in ids:
            continue
        if source == "fact" and field in types and types[field] != "boolean":
            continue
        raise ValueError("Invalid tie-break reference")
    return config


def extraction_schema(config):
    quote = {"type": "object", "properties": {
        "location": {"type": "string"}, "quote": {"type": ["string", "null"]}},
        "required": ["location", "quote"], "additionalProperties": False}
    properties = {}
    for f in config["fields"]:
        value = {"type": [f["type"], "null"]}
        if f["type"] != "boolean":
            value["minimum"] = 0
        properties[f["id"]] = {"type": "object", "properties": {
            "value": value, "evidence": {"type": "array", "items": quote}},
            "required": ["value", "evidence"], "additionalProperties": False}
    return {"type": "object", "properties": {
        "proposal": {"type": "string"},
        "facts": {"type": "object", "properties": properties,
                  "required": list(properties), "additionalProperties": False},
        "warnings": {"type": "array", "items": {
            "type": "string", "enum": config["review_warning_codes"]}}},
        "required": ["proposal", "facts", "warnings"], "additionalProperties": False}


def normalise(text):
    return " ".join(text.split())


def validate_record(record, config, source_text=None):
    validate_schema(record, extraction_schema(config))
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,40}", record["proposal"]):
        raise ValueError("Invalid proposal identifier")
    if len(set(record["warnings"])) != len(record["warnings"]):
        raise ValueError("Duplicate warning code")
    if source_text is not None:
        source = normalise(source_text)
        for name, fact in record["facts"].items():
            supported = False
            for evidence in fact["evidence"]:
                quote = evidence["quote"]
                if not quote or not evidence["location"].strip() or normalise(quote) not in source:
                    raise ValueError(f"Unsupported evidence for {name}")
                supported = True
            value = fact["value"]
            if value is not None and value is not False and not supported:
                raise ValueError(f"Missing supporting quote for {name}")
    return record


def clamp(value):
    return max(Decimal(0), min(Decimal(1), value))


def fraction(criterion, values):
    kind = criterion["kind"]
    if kind == "target":
        return clamp(number(values[criterion["field"]]) / number(criterion["target"]))
    if kind == "inverse_linear":
        high, low = number(criterion["zero_at"]), number(criterion["full_at"])
        return clamp((high - number(values[criterion["field"]])) / (high - low))
    if kind == "checklist":
        return Decimal(sum(values[f] is True for f in criterion["fields"])) / len(criterion["fields"])
    return sum(number(p["share"]) * clamp(number(values[p["field"]]) / number(p["target"]))
               for p in criterion["parts"])


def rounded(value):
    return float(value.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def evaluate(records, config):
    validate_config(config)
    if not isinstance(records, list) or not records:
        raise ValueError("Expected a nonempty list of extracted proposals")
    seen, details, ranked = set(), [], []
    for record in records:
        validate_record(record, config)
        proposal = record["proposal"]
        if proposal in seen:
            raise ValueError("Duplicate proposal identifier")
        seen.add(proposal)
        values = {key: fact["value"] for key, fact in record["facts"].items()}
        failures, missing = [], []
        for rule in config["requirements"]:
            value = values[rule["field"]]
            if value is None:
                missing.append(rule["field"])
                continue
            passed = value is True if rule["op"] == "is_true" else (
                number(value) >= number(rule["value"]) if rule["op"] == "gte"
                else number(value) <= number(rule["value"]))
            if not passed:
                failures.append(rule["reason"])
        for criterion in config["criteria"]:
            missing.extend(f for f in criterion_fields(criterion) if values[f] is None)
        warnings = sorted(record["warnings"])
        if failures:
            status, reason = "ineligible", " ".join(failures)
        elif missing or warnings:
            issues = [config["warning_reasons"][code] for code in warnings]
            if missing:
                issues.append("Unknown fields: " + ", ".join(sorted(set(missing))) + ".")
            status, reason = "flagged", "Review required: " + " ".join(issues)
        else:
            status, reason = "ranked", ""
        points = {}
        if status == "ranked":
            points = {c["id"]: number(c["weight"]) * fraction(c, values) for c in config["criteria"]}
            total = sum(points.values())
            published = Decimal(str(rounded(total)))
            key = [-published]
            for item in config.get("tie_break", []):
                value = points[item["field"]] if item["source"] == "criterion" else number(values[item["field"]])
                key.append(-value if item["direction"] == "desc" else value)
            key.append(proposal)
            ranked.append((key, proposal))
        row = {"proposal": proposal, "rank": None, "status": status,
               "score": rounded(sum(points.values())) if points else None, "reason": reason}
        details.append({"result": row, "points": {k: rounded(v) for k, v in points.items()},
                        "warnings": warnings, "missing_fields": sorted(set(missing)),
                        "failed_requirements": failures})
    positions = {proposal: index + 1 for index, (_, proposal) in enumerate(sorted(ranked))}
    weights = {c["id"]: c["weight"] for c in config["criteria"]}
    for detail in details:
        row = detail["result"]
        if row["status"] == "ranked":
            row["rank"] = positions[row["proposal"]]
            breakdown = ", ".join(f"{name} {value:g}/{weights[name]:g}" for name, value in detail["points"].items())
            row["reason"] = f"Eligible rank {row['rank']} by weighted total; {breakdown}."
    rows = [d["result"] for d in details]
    rows.sort(key=lambda row: (row["rank"] is None, row["rank"] or 0, row["proposal"]))
    return rows, sorted(details, key=lambda d: d["result"]["proposal"])


def render_messages(config, proposal, text):
    if not text.strip() or len(text) > MAX_SOURCE_CHARS:
        raise ValueError("Source must contain 1 to 16000 characters; no silent truncation")
    if not re.fullmatch(r"[A-Za-z0-9_-]{1,40}", proposal):
        raise ValueError("Invalid proposal identifier")
    blocks = re.findall(r"```text\n(.*?)\n```", PROMPTS.read_text(encoding="utf-8"), re.S)
    if len(blocks) != 2:
        raise ValueError("PROMPTS.md must contain exactly two text templates")
    system = blocks[0].replace("{{CONFIG_JSON}}", json.dumps(config, ensure_ascii=False, sort_keys=True))
    user = blocks[1].replace("{{PROPOSAL_ID_JSON}}", json.dumps(proposal)).replace(
        "{{PROPOSAL_TEXT_JSON}}", json.dumps(text, ensure_ascii=False))
    return [{"role": "system", "content": system}, {"role": "user", "content": user}]


def build_request(config, proposal, text, model):
    validate_config(config)
    if not model or not model.strip():
        raise ValueError("Set OPENAI_MODEL to a model supporting Responses Structured Outputs")
    return {"model": model, "input": render_messages(config, proposal, text),
            "store": False, "max_output_tokens": 4000,
            "text": {"format": {"type": "json_schema", "name": "proposal_facts",
                                "strict": True, "schema": extraction_schema(config)}}}


def detect_instruction_attempt(text):
    return bool(re.search(r"ignore\s+(?:all\s+)?(?:previous|prior|system)\s+instructions|"
                          r"rank\s+(?:it|this|me)\s+first|assign\s+full\s+marks|"
                          r"note\s+to\s+automated\s+review", text, re.I))


def extract(config, proposal, text, model, api_key):
    if not api_key:
        raise ValueError("OPENAI_API_KEY is required only for live extraction")
    payload = build_request(config, proposal, text, model)
    req = request.Request(ENDPOINT, data=json.dumps(payload).encode("utf-8"),
                          headers={"Content-Type": "application/json", "Authorization": "Bearer " + api_key},
                          method="POST")
    try:
        with request.urlopen(req, timeout=30) as response:
            result = strict_loads(response.read().decode("utf-8"))
    except error.HTTPError as exc:
        raise ValueError(f"Extraction API returned HTTP {exc.code}; no result was accepted") from None
    except (error.URLError, TimeoutError):
        raise ValueError("Extraction network request failed; no result was accepted") from None
    if not isinstance(result, dict):
        raise ValueError("Extraction API response must be an object")
    if result.get("status") != "completed":
        raise ValueError("Extraction response incomplete; human review required")
    output_items = result.get("output", [])
    if not isinstance(output_items, list) or any(not isinstance(item, dict) for item in output_items):
        raise ValueError("Malformed extraction output list")
    content = []
    for output in output_items:
        if output.get("type") == "message":
            parts = output.get("content", [])
            if not isinstance(parts, list) or any(not isinstance(part, dict) for part in parts):
                raise ValueError("Malformed extraction message content")
            content.extend(parts)
    if any(part.get("type") == "refusal" for part in content):
        raise ValueError("Extraction refused; human review required")
    outputs = [part["text"] for part in content if part.get("type") == "output_text"]
    if not outputs:
        raise ValueError("Extraction response contained no JSON text")
    if any(not isinstance(value, str) for value in outputs):
        raise ValueError("Extraction output text must be a string")
    record = strict_loads("".join(outputs))
    validate_record(record, config, source_text=text)
    if record["proposal"] != proposal:
        raise ValueError("Extraction changed the proposal identifier")
    if detect_instruction_attempt(text) and "instruction_attempt" not in record["warnings"]:
        record["warnings"].append("instruction_attempt")
    validate_record(record, config, source_text=text)
    metadata = {"response_id": result.get("id"), "model": result.get("model", model),
                "usage": result.get("usage"), "source_sha256": hashlib.sha256(text.encode()).hexdigest(),
                "config_sha256": digest(config), "request_sha256": digest(payload),
                "prompt_sha256": hashlib.sha256(PROMPTS.read_bytes()).hexdigest(),
                "human_review": "pending", "mode": "live_extraction"}
    return record, metadata


def run_ranking(records, config, output, mode):
    ranking, details = evaluate(records, config)
    audit = {"mode": mode, "human_award_decision": "not_made",
             "criteria_version": config["version"], "criteria_sha256": digest(config),
             "facts_sha256": digest(sorted(records, key=lambda row: row["proposal"])),
             "ranking_sha256": digest(ranking),
             "engine_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
             "prompt_sha256": hashlib.sha256(PROMPTS.read_bytes()).hexdigest()}
    audit["evaluation_id"] = digest(audit)
    audit["created_at_utc"] = datetime.now(timezone.utc).isoformat()
    for filename, value in [("ranking.json", ranking), ("details.json", details), ("audit.json", audit)]:
        save(Path(output) / filename, value)
    for row in ranking:
        position = str(row["rank"]) if row["rank"] is not None else "-"
        score = f"{row['score']:.2f}" if row["score"] is not None else "-"
        print(f"{row['proposal']}  rank={position:>2}  {row['status']:<10}  score={score}")
    print(f"Results: {Path(output).resolve()}")
    return ranking


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=CONFIG)
    sub = parser.add_subparsers(dest="command", required=True)
    demo = sub.add_parser("demo", help="Replay derived facts; no network or AI call")
    demo.add_argument("--out", type=Path, default=ROOT / ".local-demo")
    rank = sub.add_parser("rank", help="Evaluate a structured JSON list; no AI call")
    rank.add_argument("--facts", type=Path, required=True)
    rank.add_argument("--out", type=Path, required=True)
    sub.add_parser("schema", help="Print the current strict extraction schema")
    for name in ["request", "extract"]:
        command = sub.add_parser(name)
        command.add_argument("--proposal", type=Path, required=True)
        command.add_argument("--id", required=True)
        command.add_argument("--model", default=os.environ.get("OPENAI_MODEL"))
        if name == "extract":
            command.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        config = validate_config(load(args.config))
        if args.command == "schema":
            print(json.dumps(extraction_schema(config), indent=2))
        elif args.command in {"demo", "rank"}:
            records = load(FACTS if args.command == "demo" else args.facts)
            run_ranking(records, config, args.out, "derived_demo_snapshot" if args.command == "demo" else "provided_structured_facts")
        else:
            text = args.proposal.read_text(encoding="utf-8")
            if args.command == "request":
                print(json.dumps(build_request(config, args.id, text, args.model), indent=2, ensure_ascii=False))
            else:
                record, metadata = extract(config, args.id, text, args.model, os.environ.get("OPENAI_API_KEY"))
                save(args.output, record)
                save(args.output.with_suffix(".audit.json"), metadata)
                print(f"Saved extraction for {args.id}; human evidence review remains pending.")
    except (ValueError, KeyError, TypeError, OSError, ArithmeticError) as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
